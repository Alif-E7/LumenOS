"""
Data Provenance and Semantic Classification Framework.

Strictly distinguishes between:
  1. REAL NASA/REFERENCE DATA (Authoritative empirical measurements)
  2. SIMULATED SPACECRAFT OBSERVATION (Telemetry generated by player's spacecraft instruments)
  3. SIMULATED ENVIRONMENT/GROUND TRUTH (Synthesized ground-truth state created by physics engine)
  4. MODEL OR AI PREDICTION (Machine learning or predictive model estimations that may be inaccurate)

Crucial Rule:
  NASA FIRMS active fire detections are real external satellite measurements, NOT images
  or detections produced by the fictional LumenOS spacecraft, and are not flawless ground truth.
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Optional
from pydantic import BaseModel, Field


class DataProvenance(str, Enum):
    """Canonical 4-tier semantic provenance categories for all LumenOS data."""
    REAL_NASA_REFERENCE = "REAL_NASA_REFERENCE"
    SIMULATED_SPACECRAFT = "SIMULATED_SPACECRAFT"
    SIMULATED_ENVIRONMENT = "SIMULATED_ENVIRONMENT"
    MODEL_PREDICTION = "MODEL_PREDICTION"


class DataProvenanceMetadata(BaseModel):
    """
    Standardized provenance metadata attached to data payloads, observations,
    and reference records.
    """
    provenance_type: DataProvenance = Field(
        description="Semantic category classifying data authority and generation origin."
    )
    source_id: str = Field(
        description="Unique identifier of data product in the Data & Sources Register."
    )
    product_name: str = Field(
        description="Official name of the dataset, instrument, or simulator engine."
    )
    provider: str = Field(
        description="Publishing agency or generating subsystem."
    )
    attribution_label: str = Field(
        description="Short human-readable attribution string for UI display."
    )
    is_authoritative: bool = Field(
        default=False,
        description="True only if sourced from verified real-world empirical products (NASA, NOAA, ESA)."
    )
    educational_disclaimer: str = Field(
        default="",
        description="Required educational clarity statement preventing confusion between real and simulated data."
    )
    timestamp_utc: Optional[str] = Field(
        default=None,
        description="ISO 8601 UTC timestamp of acquisition or generation."
    )
    quality_flag: Optional[str] = Field(
        default=None,
        description="Empirical or synthetic quality level (e.g. 'nominal', 'high', 'uncalibrated')."
    )
    confidence_pct: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=100.0,
        description="Statistical confidence score if applicable."
    )


