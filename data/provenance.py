def create_provenance_meta(
    provenance_type: DataProvenance,
    source_id: str,
    product_name: str,
    provider: str,
    attribution_label: str,
    is_authoritative: bool | None = None,
    educational_disclaimer: str = "",
    timestamp_utc: Optional[str] = None,
    quality_flag: Optional[str] = None,
    confidence_pct: Optional[float] = None,
) -> DataProvenanceMetadata:
    """Helper to build a validated DataProvenanceMetadata instance."""
    auth = is_authoritative if is_authoritative is not None else (provenance_type == DataProvenance.REAL_NASA_REFERENCE)
    disc = educational_disclaimer or PROVENANCE_DISPLAY_CONFIG[provenance_type]["disclaimer"]
    return DataProvenanceMetadata(
        provenance_type=provenance_type,
        source_id=source_id,
        product_name=product_name,
        provider=provider,
        attribution_label=attribution_label,
        is_authoritative=auth,
        educational_disclaimer=disc,
        timestamp_utc=timestamp_utc,
        quality_flag=quality_flag,
        confidence_pct=confidence_pct,
    )

