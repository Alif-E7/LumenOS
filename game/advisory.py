# ── Predictive Workload Scheduler ────────────────────────────────────────────


class LumenOSPredictiveScheduler:
    """
    Signature LumenOS Predictive Workload Scheduler.
    
    Physics-grounded 5-minute forward state predictor and decision advisor.
    - Zero Future Information Leakage: Operates strictly on instantaneous state S_t.
    - Predicts continuous temperature, battery, power, processor, and comms trends.
    - Emits actionable recommendations with plain-language explanations.
    - Tracks MAE, RMSE, warning precision/recall, and mission-level utility.
    """

    def __init__(
        self,
        horizon_steps: int = 5,
        time_step_seconds: float = 60.0,
        auto_pilot_enabled: bool = False,
    ):
        self.horizon_steps = horizon_steps
        self.time_step_seconds = time_step_seconds
        self.auto_pilot_enabled = auto_pilot_enabled
        self.auto_pilot_authorized_by: Optional[str] = None

        # Internal collections
        self.active_forecast: Optional[ForecastWindow] = None
        self.active_recommendations: dict[str, AdvisoryRecommendation] = {}
        self.all_forecasts: list[ForecastWindow] = []
        self.prediction_accuracy_log: list[PredictionAccuracyRecord] = []
        self.recommendation_history: list[AdvisoryRecommendation] = []
        self._future_step_predictions: dict[int, list[tuple[int, ForecastStepPrediction]]] = defaultdict(list)

        # Classification counters
        self.true_positive_warnings: int = 0
        self.false_positive_warnings: int = 0
        self.missed_warnings_count: int = 0
        self.warning_lead_times: list[float] = []

    # ── 1. Forward Physics State Extrapolation (No Future Leakage) ────────────

    def generate_forecast(
        self,
        current_step_or_snap: Any,
        sim_runner: Any = None,
        horizon_steps: Optional[int] = None,
        step_seconds: Optional[float] = None,
        time_step_seconds: Optional[float] = None,
    ) -> ForecastWindow:
        """
        Extrapolate spacecraft physical states forward over the forecast horizon.
        
        Strict constraint: Uses ONLY physics models, current states, and Keplerian orbital
        mechanics known at step t. Does NOT read future stochastic events or RNG rolls.
        """
        h_steps = horizon_steps or self.horizon_steps
        dt = step_seconds or time_step_seconds or self.time_step_seconds

        # Unpack inputs
        if isinstance(current_step_or_snap, dict):
            snap = current_step_or_snap
            current_step = int(snap.get("step", 0))
            sim_time = float(snap.get("sim_time", current_step * dt))
            curr_temp = float(snap.get("temp_c", snap.get("temperature_c", 20.0)))
            curr_soc = float(snap.get("battery_soc", snap.get("battery_soc_pct", 100.0)))
            batt_cap_wh = float(snap.get("battery_capacity_wh", 400.0))
            curr_soc_wh = float(snap.get("battery_charge_wh", batt_cap_wh * (curr_soc / 100.0)))
            solar_power_w = float(snap.get("solar_power_w", 0.0))
            total_load_w = float(snap.get("total_power_draw_w", snap.get("total_load_w", 85.0)))
            curr_storage_mb = float(snap.get("storage_used_mb", 0.0))
            total_storage_mb = float(snap.get("storage_capacity_mb", 32768.0))
            max_safe_temp_c = float(snap.get("temp_max_c", 50.0))
            min_safe_temp_c = float(snap.get("temp_min_c", -20.0))
            sunlit = bool(snap.get("sunlit", True))
            c_thermal = 36000.0
            rad_area = 1.5
            emissivity = 0.7
            alpha = 0.6
            solar_area = 2.5
            solar_eff = 0.28
        else:
            current_step = int(current_step_or_snap)
            sim_time = current_step * dt

            core = getattr(sim_runner, "_sim", sim_runner)
            power_model = getattr(core, "_power", None)
            thermal_model = getattr(core, "_thermal", None)
            workload_model = getattr(core, "_workload", None)
            storage_model = getattr(core, "_storage", None)
            orbit_model = getattr(core, "_orbital", getattr(core, "_orbit", None))

            curr_temp = getattr(thermal_model.state, "temperature_c", 20.0) if thermal_model else 20.0
            curr_soc = getattr(power_model.state, "battery_soc_pct", 100.0) if power_model else 100.0
            curr_soc_wh = getattr(power_model.state, "battery_soc_wh", 360.0) if power_model else 360.0
            batt_cap_wh = getattr(power_model.config, "battery_capacity_wh", 400.0) if power_model else 400.0
            total_load_w = getattr(power_model.state, "total_load_w", 85.0) if power_model else 85.0
            solar_power_w = getattr(power_model.state, "solar_output_w", 200.0) if power_model else 200.0
            curr_storage_mb = getattr(storage_model.state, "used_mb", 0.0) if storage_model else 0.0
            total_storage_mb = getattr(storage_model.config, "capacity_mb", 32768.0) if storage_model else 32768.0
            max_safe_temp_c = (getattr(thermal_model.config, "safe_temp_max_k", 323.15) - 273.15) if thermal_model else 50.0
            min_safe_temp_c = (getattr(thermal_model.config, "safe_temp_min_k", 253.15) - 273.15) if thermal_model else -20.0
            sunlit = not getattr(power_model.state, "in_eclipse", False) if power_model else True
            c_thermal = getattr(thermal_model.config, "thermal_mass_j_per_k", 36000.0) if thermal_model else 36000.0
            rad_area = getattr(thermal_model.config, "radiator_area_m2", 1.5) if thermal_model else 1.5
            emissivity = getattr(thermal_model.config, "radiator_emissivity", 0.7) if thermal_model else 0.7
            alpha = getattr(thermal_model.config, "absorptivity", 0.6) if thermal_model else 0.6
            solar_area = getattr(power_model.config, "solar_panel_area_m2", 2.5) if power_model else 2.5
            solar_eff = getattr(power_model.config, "cell_efficiency", 0.28) if power_model else 0.28

        stefan_boltzmann = 5.670374419e-8
        t_sink_k = 3.0
        orbit_period_s = 5520.0  # ~92 minutes LEO
        eclipse_fraction_est = 0.35

        # Forward integration
        predictions: list[ForecastStepPrediction] = []
        sim_temp = curr_temp
        sim_soc_wh = curr_soc_wh
        sim_storage = curr_storage_mb
        hazards_detected: list[HazardType] = []

        for step_idx in range(1, h_steps + 1):
            f_step = current_step + step_idx
            f_elapsed = sim_time + (step_idx * dt)
            horizon_s = step_idx * dt

            # Expanding epistemic uncertainty bounds
            sigma_t = 0.5 * step_idx
            sigma_soc = 0.6 * step_idx

            # Orbital position & geometric eclipse estimation without future leakage
            phase_in_orbit = (f_elapsed % orbit_period_s) / orbit_period_s
            in_eclipse_est = (not sunlit) or (phase_in_orbit > (1.0 - eclipse_fraction_est))

            # Solar generation
            solar_flux = 0.0 if in_eclipse_est else 1361.0
            solar_gen_w = (solar_flux * solar_area * solar_eff) if not in_eclipse_est else 0.0
            if not in_eclipse_est and solar_power_w > 0:
                solar_gen_w = max(solar_gen_w, solar_power_w)

            # Electrical balance
            net_p = solar_gen_w - total_load_w
            delta_e_wh = (net_p * dt) / 3600.0
            sim_soc_wh = max(0.0, min(batt_cap_wh, sim_soc_wh + delta_e_wh))
            sim_soc_pct = (sim_soc_wh / max(1.0, batt_cap_wh)) * 100.0

            # Thermal heat balance ODE: C * (dT/dt) = Q_in - Q_out
            q_solar_in = (solar_flux * alpha * (solar_area * 0.4)) if not in_eclipse_est else 0.0
            q_internal = total_load_w * 0.85
            t_kelvin = sim_temp + 273.15
            q_rad_out = emissivity * stefan_boltzmann * rad_area * (pow(t_kelvin, 4) - pow(t_sink_k, 4))
            net_q_w = (q_solar_in + q_internal) - q_rad_out
            delta_t_c = (net_q_w * dt) / c_thermal
            sim_temp += delta_t_c

            # Solid-state storage accumulation
            sim_storage = min(total_storage_mb, sim_storage + 12.0)

            # Hazard checks
            pred_therm_hazard = (sim_temp >= max_safe_temp_c - 1.0) or (sim_temp <= min_safe_temp_c + 2.0)
            pred_batt_hazard = sim_soc_pct <= 25.0
            pred_storage_hazard = sim_storage >= (total_storage_mb * 0.95)

            if pred_therm_hazard:
                hazards_detected.append(HazardType.THERMAL_OVERHEAT)
            if pred_batt_hazard:
                hazards_detected.append(HazardType.BATTERY_DEPLETION)
            if pred_storage_hazard:
                hazards_detected.append(HazardType.STORAGE_OVERFLOW)

            p_step = ForecastStepPrediction(
                step=f_step,
                elapsed_seconds=f_elapsed,
                time_seconds=f_elapsed,
                horizon_seconds=horizon_s,
                temperature_c=round(sim_temp, 2),
                battery_soc=round(sim_soc_pct, 2),
                battery_soc_pct=round(sim_soc_pct, 2),
                power_demand_w=round(total_load_w, 2),
                power_generation_w=round(solar_gen_w, 2),
                power_net_w=round(net_p, 2),
                net_power_w=round(net_p, 2),
                cpu_usage_pct=round(min(100.0, total_load_w * 0.5), 1),
                storage_used_mb=round(sim_storage, 1),
                in_eclipse=in_eclipse_est,
                uncertainty_temp_c=round(sigma_t, 2),
                uncertainty_soc_pct=round(sigma_soc, 2),
                uncertainty_temperature_c=round(sigma_t, 2),
                uncertainty_battery_soc=round(sigma_soc, 2),
                predicted_thermal_hazard=pred_therm_hazard,
                predicted_battery_hazard=pred_batt_hazard,
                predicted_storage_hazard=pred_storage_hazard,
            )
            predictions.append(p_step)
            self._future_step_predictions[f_step].append((current_step, p_step))

        # Generate Actionable Recommendations based on hazards
        new_recs = self._generate_recommendations(current_step, dt, predictions, max_safe_temp_c)

        for rec in new_recs:
            self.active_recommendations[rec.recommendation_id] = rec
            self.recommendation_history.append(rec)

        window = ForecastWindow(
            origin_step=current_step,
            current_step=current_step,
            horizon_steps=h_steps,
            time_step_seconds=dt,
            predictions=predictions,
            steps=predictions,
            predicted_hazards=list(set(hazards_detected)),
            recommendations=new_recs,
            model_provenance=DataProvenance.MODEL_PREDICTION.value,
        )

        self.active_forecast = window
        self.all_forecasts.append(window)
        return window

    def _generate_recommendations(
        self,
        current_step: int,
        dt: float,
        predictions: list[ForecastStepPrediction],
        max_safe_temp_c: float,
    ) -> list[AdvisoryRecommendation]:
        recs: list[AdvisoryRecommendation] = []

        first_therm = next((p for p in predictions if p.predicted_thermal_hazard), None)
        first_batt = next((p for p in predictions if p.predicted_battery_hazard), None)
        first_stor = next((p for p in predictions if p.predicted_storage_hazard), None)

        if first_therm:
            lead_time = max(60.0, (first_therm.step - current_step) * dt)
            recs.append(
                AdvisoryRecommendation(
                    origin_step=current_step,
                    step_created=current_step,
                    time_created=current_step * dt,
                    lead_time_seconds=lead_time,
                    horizon_seconds=lead_time,
                    hazard_type=HazardType.THERMAL_OVERHEAT,
                    category="thermal",
                    severity="warning",
                    title="Predictive Load Throttle",
                    action_type="reduce_workload",
                    params={"target_cpu_pct": 25.0},
                    parameters={"target_cpu_pct": 25.0},
                    target_role="systems_engineer",
                    priority=RecommendationPriority.HIGH,
                    plain_language_explanation=f"Thermal margin predicted to drop in {int(lead_time)}s as component temperature approaches {first_therm.temperature_c:.1f}°C (max {max_safe_temp_c:.1f}°C).",
                    explanation=f"Thermal margin predicted to drop in {int(lead_time)}s as component temperature approaches {first_therm.temperature_c:.1f}°C (max {max_safe_temp_c:.1f}°C).",
                    expected_benefit="Averts thermal throttling and protects sensor stability.",
                    possible_cost_tradeoff="Slows background science processing tasks by 25%.",
                    cost_tradeoff="Slows background science processing tasks by 25%.",
                    influencing_variables=["temp_c", "total_power_draw_w", "cpu_usage_pct"],
                    confidence_score=0.92,
                )
            )

        if first_batt:
            lead_time = max(60.0, (first_batt.step - current_step) * dt)
            severity = "critical" if first_batt.battery_soc <= 20.0 else "warning"
            action = "enter_safe_mode" if severity == "critical" else "reduce_instrument_activity"
            recs.append(
                AdvisoryRecommendation(
                    origin_step=current_step,
                    step_created=current_step,
                    time_created=current_step * dt,
                    lead_time_seconds=lead_time,
                    horizon_seconds=lead_time,
                    hazard_type=HazardType.BATTERY_DEPLETION,
                    category="power",
                    severity=severity,
                    title="Conserve Battery Reserve",
                    action_type=action,
                    params={"instrument_id": "thermal_ir"},
                    parameters={"instrument_id": "thermal_ir"},
                    target_role="systems_engineer",
                    priority=RecommendationPriority.CRITICAL if severity == "critical" else RecommendationPriority.HIGH,
                    plain_language_explanation=f"Battery depletion predicted to reach critical buffer ({first_batt.battery_soc:.1f}%) within {int(lead_time)}s.",
                    explanation=f"Battery depletion predicted to reach critical buffer ({first_batt.battery_soc:.1f}%) within {int(lead_time)}s.",
                    expected_benefit="Preserves emergency avionics power reserve and prevents spacecraft blackout.",
                    possible_cost_tradeoff="Suspends science observation activity during eclipse pass.",
                    cost_tradeoff="Suspends science observation activity during eclipse pass.",
                    influencing_variables=["battery_soc", "solar_output_w", "total_power_draw_w"],
                    confidence_score=0.90,
                )
            )

        if first_stor:
            lead_time = max(60.0, (first_stor.step - current_step) * dt)
            recs.append(
                AdvisoryRecommendation(
                    origin_step=current_step,
                    step_created=current_step,
                    time_created=current_step * dt,
                    lead_time_seconds=lead_time,
                    horizon_seconds=lead_time,
                    hazard_type=HazardType.STORAGE_OVERFLOW,
                    category="storage",
                    severity="warning",
                    title="Solid-State Storage Buffer Pressure",
                    action_type="transmit_critical_data",
                    params={"amount_mb": 500.0},
                    parameters={"amount_mb": 500.0},
                    target_role="science_officer",
                    priority=RecommendationPriority.MEDIUM,
                    plain_language_explanation=f"Storage buffer projected to exceed 95% capacity in {int(lead_time)}s.",
                    explanation=f"Storage buffer projected to exceed 95% capacity in {int(lead_time)}s.",
                    expected_benefit="Frees memory space to prevent telemetry dropping or buffer overflow.",
                    possible_cost_tradeoff="Requires active transmitter RF power draw.",
                    cost_tradeoff="Requires active transmitter RF power draw.",
                    influencing_variables=["storage_used_mb", "raw_data_mb"],
                    confidence_score=0.94,
                )
            )

        return recs

    # ── 2. Player Response & Auditable Automation ─────────────────────────────

    def respond_to_recommendation(
        self,
        recommendation_id: str,
        action: str = "accept",
        response: Optional[str] = None,
        modified_parameters: Optional[dict[str, Any]] = None,
        modified_params: Optional[dict[str, Any]] = None,
        player_id: str = "operator",
        actor: Optional[str] = None,
        runtime: Optional[Any] = None,
        **kwargs: Any,
    ) -> dict[str, Any]:
        """
        Handle player/crew decision on an active recommendation:
        Accepting or modifying dispatches the corresponding command through the runtime.
        """
        chosen_action = (response or action or kwargs.get("response", "accept")).lower()
        effective_player = actor or player_id
        effective_params = modified_parameters or modified_params or kwargs.get("modified_params")

        rec = self.active_recommendations.get(recommendation_id)
        if rec is None:
            rec = next((r for r in self.recommendation_history if r.recommendation_id == recommendation_id), None)

        if rec is None:
            return {"success": False, "error": f"Recommendation '{recommendation_id}' not found"}

        now = time.time()
        rec.decision_timestamp = now
        rec.actor = effective_player
        rec.resolved_by = effective_player
        rec.resolved_step = getattr(runtime, "current_step", 0) if runtime else 0

        if chosen_action == "accept":
            rec.status = "accepted"
            rec.audit_notes = f"Accepted by {effective_player}"
            if runtime is not None:
                self._dispatch_action(rec, rec.params, effective_player, runtime)
            return {"success": True, "action": "accept", "status": "accepted", "recommendation": rec.model_dump()}

        elif chosen_action == "reject":
            rec.status = "rejected"
            rec.audit_notes = f"Rejected by {effective_player}"
            return {"success": True, "action": "reject", "status": "rejected", "recommendation": rec.model_dump()}

        elif chosen_action == "modify":
            rec.status = "modified"
            if effective_params:
                rec.params.update(effective_params)
                rec.parameters.update(effective_params)
            rec.audit_notes = f"Modified and executed by {effective_player} with params {rec.params}"
            if runtime is not None:
                self._dispatch_action(rec, rec.params, effective_player, runtime)
            return {"success": True, "action": "modify", "status": "modified", "recommendation": rec.model_dump()}

        return {"success": False, "error": f"Unknown action '{chosen_action}'"}

    def _dispatch_action(
        self,
        rec: AdvisoryRecommendation,
        params: dict[str, Any],
        actor: str,
        runtime: Any,
    ) -> None:
        """Dispatch action to the authoritative simulation runtime."""
        if hasattr(runtime, "submit_command"):
            from game.command_resolver import CommandRequest
            cmd = CommandRequest(
                actor=actor,
                role=rec.target_role,
                action_type=rec.action_type,
                params=params,
            )
            runtime.submit_command(cmd)
        elif hasattr(runtime, "action_log"):
            runtime.action_log.append({
                "actor": actor,
                "action_type": rec.action_type,
                "params": params,
                "step": getattr(runtime, "current_step", 0),
            })

    def set_automation(self, enabled: bool, player_id: str = "mission_director") -> dict[str, Any]:
        """
        Explicitly activate or deactivate automated mission scheduling.
        When active, auto-executes CRITICAL safety recommendations with complete audit trail.
        """
        self.auto_pilot_enabled = enabled
        self.auto_pilot_authorized_by = player_id if enabled else None
        return {"success": True, "enabled": enabled, "authorized_by": self.auto_pilot_authorized_by}

    def tick_automation(self, runtime: Any) -> list[dict[str, Any]]:
        """
        If automation is explicitly enabled, execute pending CRITICAL recommendations.
        """
        if not self.auto_pilot_enabled or not self.active_recommendations:
            return []

        executed: list[dict[str, Any]] = []
        for rec in list(self.active_recommendations.values()):
            if rec.status == "pending" and (rec.severity == "critical" or rec.priority == RecommendationPriority.CRITICAL):
                rec.status = "auto_executed"
                rec.decision_timestamp = time.time()
                rec.actor = "LumenOS-Autopilot"
                rec.resolved_by = "LumenOS-Autopilot"
                rec.audit_notes = "Auto-executed under explicit player authorization."
                self._dispatch_action(rec, rec.params, "LumenOS-Autopilot", runtime)
                executed.append({"action_type": rec.action_type, "recommendation_id": rec.recommendation_id})

        return executed

    # ── 3. Verification & Accuracy Scorecard (MAE, RMSE, Lead Time) ───────────

    def evaluate_actuals(
        self,
        current_step_or_snapshot: Any,
        actual_telemetry: Optional[dict[str, Any]] = None,
    ) -> list[PredictionAccuracyRecord]:
        """
        Compare prior forecasts that targeted current step against actual measured telemetry.
        """
        if actual_telemetry is None and isinstance(current_step_or_snapshot, dict):
            actual_telemetry = current_step_or_snapshot
            current_step = int(actual_telemetry.get("step", 0))
        else:
            current_step = int(current_step_or_snapshot)
            actual_telemetry = actual_telemetry or {}

        records: list[PredictionAccuracyRecord] = []
        actual_temp = float(actual_telemetry.get("temp_c", actual_telemetry.get("temperature_c", actual_telemetry.get("thermal", {}).get("temperature_c", 20.0))))
        actual_soc = float(actual_telemetry.get("battery_soc", actual_telemetry.get("battery_soc_pct", actual_telemetry.get("power", {}).get("battery_soc_pct", 100.0))))
        max_safe_temp_c = float(actual_telemetry.get("temp_max_c", 50.0))
        min_safe_temp_c = float(actual_telemetry.get("temp_min_c", -20.0))

        actual_hazard = (actual_temp >= max_safe_temp_c) or (actual_temp <= min_safe_temp_c) or (actual_soc <= 20.0)

        step_predictions = self._future_step_predictions.get(current_step, [])
        predicted_hazard_any = False

        for origin_step, pred in step_predictions:
            # Temperature evaluation
            err_t = abs(actual_temp - pred.temperature_c)
            sq_t = err_t * err_t
            within_ci_t = err_t <= pred.uncertainty_temperature_c

            rec_t = PredictionAccuracyRecord(
                forecast_id=f"fc_{origin_step}_{current_step}_temp",
                origin_step=origin_step,
                target_step=current_step,
                horizon_seconds=float((current_step - origin_step) * self.time_step_seconds),
                metric_name="temperature_c",
                predicted_value=pred.temperature_c,
                actual_value=actual_temp,
                absolute_error=round(err_t, 3),
                squared_error=round(sq_t, 3),
                uncertainty_bound=pred.uncertainty_temperature_c,
                within_confidence_interval=within_ci_t,
            )
            records.append(rec_t)
            self.prediction_accuracy_log.append(rec_t)

            # Battery SoC evaluation
            err_soc = abs(actual_soc - pred.battery_soc)
            sq_soc = err_soc * err_soc
            within_ci_soc = err_soc <= pred.uncertainty_battery_soc

            rec_soc = PredictionAccuracyRecord(
                forecast_id=f"fc_{origin_step}_{current_step}_soc",
                origin_step=origin_step,
                target_step=current_step,
                horizon_seconds=float((current_step - origin_step) * self.time_step_seconds),
                metric_name="battery_soc_pct",
                predicted_value=pred.battery_soc,
                actual_value=actual_soc,
                absolute_error=round(err_soc, 3),
                squared_error=round(sq_soc, 3),
                uncertainty_bound=pred.uncertainty_battery_soc,
                within_confidence_interval=within_ci_soc,
            )
            records.append(rec_soc)
            self.prediction_accuracy_log.append(rec_soc)

            # Check if hazard was predicted
            if pred.predicted_thermal_hazard or pred.predicted_battery_hazard or pred.predicted_storage_hazard:
                predicted_hazard_any = True
                self.warning_lead_times.append(rec_t.horizon_seconds)

        # Classification verification
        if predicted_hazard_any and actual_hazard:
            self.true_positive_warnings += 1
        elif predicted_hazard_any and not actual_hazard:
            self.false_positive_warnings += 1
        elif not predicted_hazard_any and actual_hazard:
            self.missed_warnings_count += 1

        return records

    def compute_metrics_summary(self) -> AdvisoryMetricsSummary:
        """
        Compute aggregate verification scorecard:
        - Continuous forecast MAE & RMSE for temperature and battery.
        - Threshold classification Precision, Recall, False Warnings, Missed Warnings.
        - Average warning lead time.
        - Mission-level outcome benefits.
        """
        temp_records = [r for r in self.prediction_accuracy_log if r.metric_name == "temperature_c"]
        soc_records = [r for r in self.prediction_accuracy_log if r.metric_name == "battery_soc_pct"]

        temp_mae = sum(r.absolute_error for r in temp_records) / max(1, len(temp_records)) if temp_records else 0.0
        temp_rmse = math.sqrt(sum(r.squared_error for r in temp_records) / max(1, len(temp_records))) if temp_records else 0.0

        soc_mae = sum(r.absolute_error for r in soc_records) / max(1, len(soc_records)) if soc_records else 0.0
        soc_rmse = math.sqrt(sum(r.squared_error for r in soc_records) / max(1, len(soc_records))) if soc_records else 0.0

        tp = self.true_positive_warnings
        fp = self.false_positive_warnings
        fn = self.missed_warnings_count

        precision = tp / max(1, tp + fp) if (tp + fp) > 0 else 1.0
        recall = tp / max(1, tp + fn) if (tp + fn) > 0 else 1.0
        avg_lead_time = sum(self.warning_lead_times) / max(1, len(self.warning_lead_times)) if self.warning_lead_times else 0.0

        recs = list(self.active_recommendations.values()) + [r for r in self.recommendation_history if r.recommendation_id not in self.active_recommendations]
        accepted_cnt = sum(1 for r in recs if r.status == "accepted")
        rejected_cnt = sum(1 for r in recs if r.status == "rejected")
        modified_cnt = sum(1 for r in recs if r.status == "modified")
        auto_cnt = sum(1 for r in recs if r.status == "auto_executed")

        provenance_meta = create_provenance_meta(
            provenance_type=DataProvenance.MODEL_PREDICTION,
            source_id="lumenos_predictive_scheduler",
            product_name="LumenOS Predictive Mission Management ODE Forecaster",
            provider="LumenOS Autonomous Advisory Subsystem",
            attribution_label="Predictive ODE Model",
            is_authoritative=False,
            educational_disclaimer="Model-based numerical prediction subject to epistemic uncertainty and unmodeled perturbations.",
            quality_flag="calibrated",
            confidence_pct=92.0,
        )

        return AdvisoryMetricsSummary(
            total_forecasts_generated=len(self.all_forecasts),
            evaluated_predictions_count=len(temp_records),
            evaluation_records_count=len(temp_records),
            temperature_mae_c=round(temp_mae, 3),
            continuous_forecast_mae_temp_c=round(temp_mae, 3),
            continuous_mae_temp_c=round(temp_mae, 3),
            temperature_rmse_c=round(temp_rmse, 3),
            continuous_forecast_rmse_temp_c=round(temp_rmse, 3),
            battery_mae_pct=round(soc_mae, 3),
            continuous_forecast_mae_soc_pct=round(soc_mae, 3),
            battery_rmse_pct=round(soc_rmse, 3),
            continuous_forecast_rmse_soc_pct=round(soc_rmse, 3),
            hazard_warnings_issued=len(self.recommendation_history),
            true_positives=tp,
            true_positive_warnings=tp,
            false_positives=fp,
            false_positive_warnings=fp,
            false_negatives=fn,
            missed_warnings=fn,
            precision=round(precision, 3),
            warning_precision=round(precision, 3),
            recall=round(recall, 3),
            warning_recall=round(recall, 3),
            avg_warning_lead_time_seconds=round(avg_lead_time, 1),
            average_lead_time_seconds=round(avg_lead_time, 1),
            recommendations_accepted=accepted_cnt,
            recommendations_rejected=rejected_cnt,
            recommendations_modified=modified_cnt,
            recommendations_auto_executed=auto_cnt,
            critical_threshold_violations_avoided=accepted_cnt + auto_cnt,
            science_data_protected_mb=round((accepted_cnt + auto_cnt) * 350.0, 1),
            model_provenance=DataProvenance.MODEL_PREDICTION.value,
            provenance_metadata=provenance_meta,
        )
